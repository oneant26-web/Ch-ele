// YY.MM.DD → 20YY-MM-DD
function bd(d) {
  if (!d || !d.trim()) return null;
  const s = d.replace(/\.$/, '').trim();
  const p = s.split('.');
  if (p.length !== 3 || !p[0] || !p[1] || !p[2]) return null;
  return `20${p[0]}-${p[1].padStart(2, '0')}-${p[2].padStart(2, '0')}`;
}
// XXXX-XXXX → 010-XXXX-XXXX
function ph(p) {
  if (!p || !p.trim()) return null;
  return `010-${p.trim()}`;
}
